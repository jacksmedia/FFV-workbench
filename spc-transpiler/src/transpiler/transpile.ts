/**
 * Main Transpilation Pipeline
 *
 * Flow: AST → Normalize → Quantize → Encode → Bytecode
 *
 * This orchestrates the full cross-game transpilation process.
 */

import type { GameId, SequenceAst, SequenceNode, NoteNode, TieNode, RestNode } from '@/types/ast';
import { quantizeDuration, analyzeQuantization, type QuantizationReport } from './duration-quantizer';
import { clampPitch } from './pitch-normalizer';
import {
  checkTranspileCompatibility,
  adjustPanForGame,
  type TranspileWarning,
} from './command-mapper';

/** Transpilation options */
export interface TranspileOptions {
  /** Target game format */
  targetGame: GameId;

  /** How to handle duration quantization */
  durationMode: 'quantize' | 'split' | 'error';

  /** How to handle unsupported commands */
  unsupportedMode: 'skip' | 'approximate' | 'error';

  /** Whether to preserve source comments/metadata */
  preserveMetadata: boolean;

  /** Whether to adjust tempo to compensate for timing differences */
  adjustTempo: boolean;
}

/** Default transpilation options */
export const DEFAULT_OPTIONS: TranspileOptions = {
  targetGame: 'ff6',
  durationMode: 'quantize',
  unsupportedMode: 'skip',
  preserveMetadata: true,
  adjustTempo: false,
};

/** Transpilation result */
export interface TranspileResult {
  /** Transpiled AST (same structure, modified for target game) */
  ast: SequenceAst;

  /** Generated bytecode for each track */
  bytecode: Uint8Array[];

  /** Combined bytecode with header */
  fullSequence: Uint8Array;

  /** Warnings generated during transpilation */
  warnings: TranspileWarning[];

  /** Quantization analysis */
  quantization: QuantizationReport;

  /** Statistics */
  stats: {
    sourceGame: GameId;
    targetGame: GameId;
    totalNodes: number;
    modifiedNodes: number;
    skippedNodes: number;
    bytesOriginal: number;
    bytesTranspiled: number;
  };
}

/**
 * Transpile a sequence AST from one game format to another
 */
export function transpile(
  sourceAst: SequenceAst,
  options: Partial<TranspileOptions> = {}
): TranspileResult {
  const opts: TranspileOptions = { ...DEFAULT_OPTIONS, ...options };
  const warnings: TranspileWarning[] = [];
  const allDurations: number[] = [];

  let modifiedNodes = 0;
  let skippedNodes = 0;

  // Clone AST for modification
  const targetAst: SequenceAst = {
    ...sourceAst,
    sourceGame: opts.targetGame,
    tracks: sourceAst.tracks.map(track => ({
      ...track,
      nodes: [],
    })),
  };

  // Process each track
  for (let t = 0; t < sourceAst.tracks.length; t++) {
    const sourceTrack = sourceAst.tracks[t];
    const targetTrack = targetAst.tracks[t];

    if (!sourceTrack || !targetTrack) continue;

    for (const node of sourceTrack.nodes) {
      const result = transpileNode(node, sourceAst.sourceGame, opts, warnings);

      if (result.skip) {
        skippedNodes++;
        continue;
      }

      if (result.modified) {
        modifiedNodes++;
      }

      targetTrack.nodes.push(result.node);

      // Collect durations for quantization analysis
      if (result.node.type === 'note' || result.node.type === 'tie' || result.node.type === 'rest') {
        const durationNode = result.node as NoteNode | TieNode | RestNode;
        allDurations.push(durationNode.duration);
      }
    }
  }

  // Analyze quantization
  const quantization = analyzeQuantization(allDurations, opts.targetGame);

  // Generate bytecode (placeholder - actual encoding done by game-specific encoders)
  const bytecode = targetAst.tracks.map(() => new Uint8Array(0));
  const fullSequence = new Uint8Array(0);

  return {
    ast: targetAst,
    bytecode,
    fullSequence,
    warnings,
    quantization,
    stats: {
      sourceGame: sourceAst.sourceGame,
      targetGame: opts.targetGame,
      totalNodes: sourceAst.tracks.reduce((sum, t) => sum + t.nodes.length, 0),
      modifiedNodes,
      skippedNodes,
      bytesOriginal: 0, // Calculated by encoder
      bytesTranspiled: 0,
    },
  };
}

/** Result of transpiling a single node */
interface NodeResult {
  node: SequenceNode;
  modified: boolean;
  skip: boolean;
}

/**
 * Transpile a single AST node
 */
function transpileNode(
  node: SequenceNode,
  sourceGame: GameId,
  options: TranspileOptions,
  warnings: TranspileWarning[]
): NodeResult {
  // Check compatibility
  const compat = checkTranspileCompatibility(node, sourceGame, options.targetGame);

  if (compat) {
    warnings.push(compat);

    if (compat.type === 'unsupported') {
      if (options.unsupportedMode === 'error') {
        throw new Error(compat.message);
      }
      if (options.unsupportedMode === 'skip') {
        return { node, modified: false, skip: true };
      }
    }
  }

  // Handle specific node types
  switch (node.type) {
    case 'note':
      return transpileNote(node, options, warnings);

    case 'tie':
      return transpileTie(node, options, warnings);

    case 'rest':
      return transpileRest(node, options);

    case 'pan':
      return transpilePan(node, options);

    case 'pan_fade':
      return transpilePanFade(node, options);

    default:
      // Most commands just need opcode mapping (done at encode time)
      return { node, modified: false, skip: false };
  }
}

/** Transpile a note node */
function transpileNote(
  node: NoteNode,
  options: TranspileOptions,
  warnings: TranspileWarning[]
): NodeResult {
  let modified = false;

  // Quantize duration if needed
  const quantized = quantizeDuration(node.duration, options.targetGame);
  let newDuration = node.duration;

  if (!quantized.exact) {
    if (options.durationMode === 'error') {
      throw new Error(`Duration ${node.duration} cannot be exactly represented in ${options.targetGame}`);
    }

    newDuration = quantized.ticks;
    modified = true;

    warnings.push({
      type: 'lossy',
      message: `Note duration quantized: ${node.duration} → ${quantized.ticks} ticks (${quantized.errorPercent.toFixed(1)}% error)`,
      originalNode: node,
    });
  }

  // Clamp pitch if out of range
  const clampedPitch = clampPitch(node.pitch, options.targetGame);
  if (clampedPitch.octave !== node.pitch.octave || clampedPitch.semitone !== node.pitch.semitone) {
    modified = true;
    warnings.push({
      type: 'lossy',
      message: `Pitch clamped to target range`,
      originalNode: node,
    });
  }

  if (!modified) {
    return { node, modified: false, skip: false };
  }

  return {
    node: {
      ...node,
      duration: newDuration,
      pitch: clampedPitch,
    },
    modified: true,
    skip: false,
  };
}

/** Transpile a tie node */
function transpileTie(
  node: TieNode,
  options: TranspileOptions,
  warnings: TranspileWarning[]
): NodeResult {
  const quantized = quantizeDuration(node.duration, options.targetGame);

  if (quantized.exact) {
    return { node, modified: false, skip: false };
  }

  if (options.durationMode === 'error') {
    throw new Error(`Tie duration ${node.duration} cannot be exactly represented`);
  }

  warnings.push({
    type: 'lossy',
    message: `Tie duration quantized: ${node.duration} → ${quantized.ticks} ticks`,
    originalNode: node,
  });

  return {
    node: { ...node, duration: quantized.ticks },
    modified: true,
    skip: false,
  };
}

/** Transpile a rest node */
function transpileRest(
  node: RestNode,
  options: TranspileOptions
): NodeResult {
  const quantized = quantizeDuration(node.duration, options.targetGame);

  if (quantized.exact) {
    return { node, modified: false, skip: false };
  }

  if (options.durationMode === 'error') {
    throw new Error(`Rest duration ${node.duration} cannot be exactly represented`);
  }

  return {
    node: { ...node, duration: quantized.ticks },
    modified: true,
    skip: false,
  };
}

/** Transpile a pan node (FF6 needs value adjustment) */
function transpilePan(
  node: { type: 'pan'; value: number; sourceOffset: number; sourceByte: number },
  options: TranspileOptions
): NodeResult {
  const adjustedValue = adjustPanForGame(node.value, options.targetGame);

  if (adjustedValue === node.value) {
    return { node, modified: false, skip: false };
  }

  return {
    node: { ...node, value: adjustedValue },
    modified: true,
    skip: false,
  };
}

/** Transpile a pan fade node */
function transpilePanFade(
  node: { type: 'pan_fade'; duration: number; targetValue: number; sourceOffset: number; sourceByte: number },
  options: TranspileOptions
): NodeResult {
  const adjustedValue = adjustPanForGame(node.targetValue, options.targetGame);

  if (adjustedValue === node.targetValue) {
    return { node, modified: false, skip: false };
  }

  return {
    node: { ...node, targetValue: adjustedValue },
    modified: true,
    skip: false,
  };
}

/**
 * Preview transpilation without generating bytecode
 * Useful for showing warnings before committing
 */
export function previewTranspile(
  sourceAst: SequenceAst,
  targetGame: GameId
): { warnings: TranspileWarning[]; quantization: QuantizationReport } {
  const warnings: TranspileWarning[] = [];
  const durations: number[] = [];

  for (const track of sourceAst.tracks) {
    for (const node of track.nodes) {
      const compat = checkTranspileCompatibility(node, sourceAst.sourceGame, targetGame);
      if (compat) {
        warnings.push(compat);
      }

      if (node.type === 'note' || node.type === 'tie' || node.type === 'rest') {
        const durationNode = node as NoteNode | TieNode | RestNode;
        durations.push(durationNode.duration);
      }
    }
  }

  const quantization = analyzeQuantization(durations, targetGame);

  return { warnings, quantization };
}
